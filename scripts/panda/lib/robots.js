// Panda theme — robots.txt rendering.
//
// Robots.txt is a *crawling preference* channel, not access control and not a
// privacy mechanism. The generator therefore separates three intents instead of
// writing a blanket `Disallow: /`:
//
//   search indexing        → allowed (Googlebot / OAI-SearchBot / Claude-SearchBot)
//   user-triggered fetch   → allowed (ChatGPT-User / Claude-User / Google-Agent)
//   model training         → denied  (GPTBot / ClaudeBot / Google-Extended +
//                                      the shared `__usage_ai-training` policy token)
//
// Source notes and the exact vendor wording live in docs/specs/ai-crawler-policy.md.
// Two facts shape the output:
//   * `Google-Extended` is a product *control token*, not a crawler: blocking it
//     removes Gemini training/grounding eligibility, never Google Search inclusion.
//   * `Google-Agent` is user-triggered; RFC 9309 does not govern it, so a robots
//     group is not a control surface for it. It is configurable for completeness,
//     and the generated file says so.
'use strict'

const { absoluteUrl } = require('./site-url')

// Vendor tokens, kept as data so the verifier and the docs stay in sync.
const SEARCH_TOKENS = ['Googlebot', 'OAI-SearchBot', 'Claude-SearchBot', 'Bingbot', 'DuckDuckBot', 'Baiduspider', 'YandexBot']
// Training-only crawlers. Listing each vendor token explicitly keeps the file
// auditable: a vendor rename shows up as a visible diff instead of hiding behind
// a wildcard. Order follows the vendor list in docs/specs/ai-crawler-policy.md.
const TRAINING_TOKENS = [
  'GPTBot',
  'ClaudeBot',
  'Applebot-Extended',
  'CCBot',
  'Bytespider',
  'meta-externalagent',
  'Amazonbot',
  'cohere-ai',
  'ImagesiftBot',
  'Omgili',
  'TimpiBot',
  'DuckAssistBot'
]
const CONTROL_TOKENS = ['Google-Extended']
// Fetchers a person triggers from a chat UI. They are not ordinary crawlers: the
// page is fetched on demand, so a robots group is informational for them.
const USER_TRIGGERED_TOKENS = ['ChatGPT-User', 'Claude-User', 'Perplexity-User']

// draft-ietf-aipref-attach: a usage preference, not a crawl directive. Emitted next
// to the `__usage_ai-training` policy token because vendors are at different stages
// of adopting the shared signal; a site owner gets both without choosing.
const CONTENT_USAGE_TRAIN_NONE = 'train-ai=n'
const CONTENT_USAGE_TRAIN_ALLOWED = 'train-ai=y'

const POLICIES = ['balanced', 'permissive', 'custom']
const GOOGLE_AGENT_MODES = ['omit', 'allow', 'disallow']
const USAGE_MODES = ['deny', 'allow', 'omit']

const HEADER = [
  '# robots.txt generated by hexo-theme-panda',
  '#',
  '# Search indexing and user-triggered agent access are allowed.',
  '# Model-training crawlers are asked not to use this content for training.',
  '#',
  '# robots.txt is a crawling preference, not access control: it does not protect',
  '# private data and it does not stop a determined crawler. Use authentication,',
  '# a CDN/WAF policy or server-side rules for those.'
]

function line (value) {
  return String(value == null ? '' : value).replace(/[\r\n]+/g, ' ').trim()
}

function groupBlock (tokens, rules) {
  const header = [].concat(tokens).filter(Boolean).map(token => `User-agent: ${line(token)}`)
  if (!header.length) return null
  const body = rules.filter(Boolean).map(rule => line(rule))
  if (!body.length) return null
  return `${header.join('\n')}\n${body.join('\n')}`
}

function normalizeRules (rules) {
  return (Array.isArray(rules) ? rules : []).map(rule => line(rule)).filter(Boolean)
}

function renderSitemapLine (sitemapUrl) {
  // sitemaps.org and Google both require a fully qualified URL here.
  if (!sitemapUrl) return null
  return `Sitemap: ${sitemapUrl}`
}

/**
 * @param {object} options
 * @param {'balanced'|'permissive'|'custom'} options.policy
 * @param {string[]} options.disallow            paths disallowed site-wide
 * @param {string[]} options.allow               paths explicitly allowed site-wide
 * @param {Array}    options.customGroups        {userAgents, allow, disallow, contentUsage, note}
 * @param {string}   [options.sitemapUrl]        absolute URL
 * @param {'deny'|'allow'|'omit'} options.usageAiTraining
 * @param {'omit'|'allow'|'disallow'} options.googleAgent
 * @returns {string}
 */
function renderRobots (options = {}) {
  const policy = POLICIES.includes(options.policy) ? options.policy : 'balanced'
  const usage = USAGE_MODES.includes(options.usageAiTraining) ? options.usageAiTraining : 'deny'
  const googleAgent = GOOGLE_AGENT_MODES.includes(options.googleAgent) ? options.googleAgent : 'omit'
  const disallow = normalizeRules(options.disallow)
  const allow = normalizeRules(options.allow)
  const customGroups = Array.isArray(options.customGroups) ? options.customGroups : []

  const blocks = []

  // Site-wide group first: the fallback every RFC 9309 crawler uses. `permissive`
  // stops here — one wildcard group and nothing AI-specific.
  blocks.push(groupBlock('*', ['Allow: /', ...allow.map(p => `Allow: ${p}`), ...disallow.map(p => `Disallow: ${p}`)]))

  if (policy === 'balanced') {
    blocks.push([
      '# Search indexing: allowed, so the site stays discoverable.',
      groupBlock(SEARCH_TOKENS, ['Allow: /', ...allow.map(p => `Allow: ${p}`), ...disallow.map(p => `Disallow: ${p}`)])
    ].filter(Boolean).join('\n'))

    blocks.push([
      '# User-triggered fetches (a person asking a chat assistant about this page):',
      '# allowed, because the answer links back to the source.',
      groupBlock(USER_TRIGGERED_TOKENS, ['Allow: /', ...disallow.map(p => `Disallow: ${p}`)])
    ].filter(Boolean).join('\n'))

    blocks.push([
      '# Model training: opt out.',
      groupBlock(TRAINING_TOKENS, ['Disallow: /', `Content-Usage: ${CONTENT_USAGE_TRAIN_NONE}`])
    ].filter(Boolean).join('\n'))

    blocks.push([
      '# Control token, not a crawler: affects Gemini training and grounding only,',
      '# never Google Search inclusion or ranking.',
      groupBlock(CONTROL_TOKENS, ['Disallow: /'])
    ].filter(Boolean).join('\n'))

    if (usage !== 'omit') {
      // draft-kelley-aipref-training-preference-signal: a policy token in the
      // User-Agent line; wildcard groups must not match it. A disallowed path
      // expresses "do not use this content for training".
      // Both plain `Allow`/`Disallow` (a robots gate) and the AIPREF
      // `Content-Usage` preference, so a vendor reading either gets the same answer.
      blocks.push([
        '# Shared AIPREF training preference (Internet-Draft, not an RFC).',
        '# Vendor-specific rules above stay in place and take precedence where',
        '# a vendor documents that behaviour.',
        groupBlock('__usage_ai-training', [
          usage === 'deny' ? 'Disallow: /' : 'Allow: /',
          `Content-Usage: ${usage === 'deny' ? CONTENT_USAGE_TRAIN_NONE : CONTENT_USAGE_TRAIN_ALLOWED}`
        ])
      ].filter(Boolean).join('\n'))
    }

  }

  if (policy === 'balanced' || policy === 'custom') {
    if (googleAgent !== 'omit') {
      const rule = googleAgent === 'allow' ? 'Allow: /' : 'Disallow: /'
      blocks.push([
        '# Google-Agent is user-triggered: RFC 9309 does not govern it, and this',
        '# group is informational only. A CDN/WAF allowlist is the real control.',
        groupBlock('Google-Agent', [rule])
      ].join('\n'))
    }
  }

  if (policy !== 'permissive') {
    for (const group of customGroups) {
      const tokens = Array.isArray(group.userAgents) ? group.userAgents : []
      const rules = [
        ...(group.allow || []).map(p => `Allow: ${p}`),
        ...(group.disallow || []).map(p => `Disallow: ${p}`),
        ...(group.contentUsage || []).map(v => `Content-Usage: ${v}`)
      ]
      if (group.note) blocks.push(`# ${line(group.note)}`)
      blocks.push(groupBlock(tokens, rules))
    }
  }

  const sitemapLine = renderSitemapLine(options.sitemapUrl)
  const parts = [
    HEADER.join('\n'),
    blocks.filter(Boolean).join('\n\n'),
    sitemapLine
  ].filter(Boolean)

  return `${parts.join('\n\n')}\n`
}

/** Build the absolute URL the Sitemap directive must carry. */
function sitemapUrlFor (siteUrl, sitemapPath) {
  const p = String(sitemapPath || 'sitemap.xml').replace(/^\/+/, '')
  return absoluteUrl(siteUrl, p)
}

/**
 * Detect generators that already claim robots.txt / sitemap.xml.
 * Names come from the plugins that actually do this:
 *   hexo-generator-robotstxt → 'robotstxt'
 *   hexo-generator-sitemap   → 'sitemap' (also 'sitemap.txt' variants are its own)
 * Baidu sitemaps register their own name and stay untouched.
 */
function detectGeneratorConflicts (hexo, kind) {
  const wanted = kind === 'robots'
    ? ['robotstxt', 'robots', 'robots-txt']
    : ['sitemap']
  const found = []
  const ext = hexo && hexo.extend && hexo.extend.generator
  if (!ext || typeof ext.get !== 'function') return found
  for (const name of wanted) {
    if (ext.get(name)) found.push(name)
  }
  return found
}

/** Human-readable remediation for a detected conflict. */
function conflictMessage (kind, names, providerKey) {
  const what = kind === 'robots' ? 'robots.txt' : 'sitemap.xml'
  const list = names.join(', ')
  return [
    `[panda] ${what}: provider is "panda" but generator "${list}" is already registered.`,
    `Only one generator may claim ${what}. Either remove the external plugin`,
    `(uninstall it, or disable it in the site config) or set ${providerKey} to "external"`,
    '(or "disabled") in _config.panda.yml.'
  ].join(' ')
}

module.exports = {
  CONTENT_USAGE_TRAIN_NONE,
  CONTENT_USAGE_TRAIN_ALLOWED,
  POLICIES,
  GOOGLE_AGENT_MODES,
  USAGE_MODES,
  SEARCH_TOKENS,
  TRAINING_TOKENS,
  CONTROL_TOKENS,
  USER_TRIGGERED_TOKENS,
  renderRobots,
  sitemapUrlFor,
  detectGeneratorConflicts,
  conflictMessage
}
